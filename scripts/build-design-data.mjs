/** Generates the visual prototype data from the canonical JSON. Not used by production. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/opportunities.json'), 'utf8'));
const L = (ar, en) => ({ ar, en });
const join = (parts) => L(parts.map(p => p.ar).filter(Boolean).join(' '), parts.map(p => p.en).filter(Boolean).join(' '));
const levels = {
  bachelor: L('بكالوريوس', "Bachelor’s"),
  master: L('ماجستير', "Master’s"),
  masters: L('ماجستير', "Master’s"),
  phd: L('دكتوراه', 'PhD'),
  beginner: L('مبتدئ', 'Beginner'),
  ms_phd: L('ماجستير/دكتوراه', 'MS/PhD')
};
function shortDeadline(o) {
  if (o.deadline.type === 'none') return L('تعلّم ذاتي', 'Self-paced');
  if (o.deadline.type !== 'fixed') return L('الموعد حسب البرنامج', 'Programme-specific deadline');
  const d = new Date(o.deadline.closes_at + 'T12:00:00Z');
  return L(new Intl.DateTimeFormat('ar', { dateStyle: 'medium', timeZone: 'UTC' }).format(d), new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium', timeZone: 'UTC' }).format(d));
}
const mapped = source.opportunities.map(o => {
  const course = o.type === 'course';
  const req = Array.from({ length: Math.max(o.requirements.ar.length, o.requirements.en.length) }, (_, i) => L(o.requirements.ar[i] || '', o.requirements.en[i] || ''));
  const certificate = course ? join([o.course.certificate.label, o.course.certificate.details]) : null;
  return {
    id: o.id,
    kind: o.type,
    title: o.title,
    provider: o.provider,
    location: o.country,
    level: L(o.levels.map(k => levels[k]?.ar || k).join(' / '), o.levels.map(k => levels[k]?.en || k).join(' / ')),
    summary: o.summary,
    description: o.description,
    requirements: req,
    benefits: [o.funding],
    field: course || o.fields.some(f => /technology|comput|artificial|data|ai|engineering/.test(f)) ? 'technology' : 'general',
    place: course ? 'online' : (o.id === 'opp-018' ? 'mixed' : 'abroad'),
    source: o.source_url,
    applicationUrl: o.application_url,
    mark: o.display.mark,
    color: o.display.color,
    deadlineLabel: shortDeadline(o),
    deadlineNote: o.deadline.note,
    statusScope: o.status_scope,
    notes: o.notes,
    certificateLabel: course ? o.course.certificate.label : null,
    certificateDetails: certificate,
    certificateUrl: course ? o.course.certificate.source_url : null,
    verificationLabel: L(`فحص مصدر آلي: ${o.verified_at}. المراجعة البشرية معلّقة.`, `Automated source check: ${o.verified_at}. Human review pending.`),
    statusLabel: course ? L('دراسة مجانية', 'Free learning') : o.id === 'opp-018' ? L('برامج مفتوحة عند الفحص', 'Open programmes at check date') : L('مفتوحة عند الفحص', 'Open at check date'),
    format: course ? o.course.duration?.label || L('تعلّم ذاتي عبر الإنترنت', 'Self-paced online learning') : L('برنامج دراسي', 'Academic programme'),
    contentLanguage: course ? L(o.course.content_languages.includes('ar') ? 'العربية والإنجليزية متاحتان ضمن اللغات' : 'الإنجليزية متحققة؛ راجع لغات المنصة', o.course.content_languages.includes('ar') ? 'Arabic and English among available languages' : 'English verified; check platform for other languages') : null
  };
});
// Interleave two categories for the visual landing page, without changing canonical data.
const scholarships = mapped.filter(o => o.kind === 'scholarship');
const courses = mapped.filter(o => o.kind === 'course');
const ordered = [];
for (let i = 0; i < Math.max(scholarships.length, courses.length); i++) {
  if (courses[i]) ordered.push(courses[i]);
  if (scholarships[i]) ordered.push(scholarships[i]);
}
const output = '// GENERATED by scripts/build-design-data.mjs. Edit data/opportunities.json instead.\n' +
  'window.OPPORTUNITIES = ' + JSON.stringify(ordered, null, 2).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + ';\n';
fs.writeFileSync(path.join(root, 'design-reference/data.js'), output);
console.log(`Generated visual reference data: ${ordered.length} records (${scholarships.length} scholarships, ${courses.length} courses).`);
